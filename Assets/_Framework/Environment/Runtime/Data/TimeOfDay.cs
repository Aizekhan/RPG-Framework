namespace RPGFramework.Environment.Runtime
{
    /// <summary>
    /// Defines the different periods of the day.
    /// </summary>
    public enum TimeOfDay
    {
        /// <summary>
        /// Early morning twilight (4-6 AM).
        /// </summary>
        Dawn,

        /// <summary>
        /// Morning hours (6-9 AM).
        /// </summary>
        Morning,

        /// <summary>
        /// Midday period (9 AM-1 PM).
        /// </summary>
        Noon,

        /// <summary>
        /// Afternoon hours (1-5 PM).
        /// </summary>
        Afternoon,

        /// <summary>
        /// Evening period (5-8 PM).
        /// </summary>
        Evening,

        /// <summary>
        /// Evening twilight (8-10 PM).
        /// </summary>
        Dusk,

        /// <summary>
        /// Night hours (10 PM-2 AM).
        /// </summary>
        Night,

        /// <summary>
        /// Deep night (2-4 AM).
        /// </summary>
        Midnight
    }
}
